#!/usr/bin/env python3
"""Emit the divergence-n2 scenario grid: ops-per-side x edit-locality.

One TOML file per cell of the RQ-1 offline-divergence sweep. Each cell is a
partition-heal with **singleton groups** (`[{nodes=[0]}, {nodes=[1]}]`), so the
two replicas diverge independently for `ops_per_group` text-splice ops and the
heal->convergence measurement times the merge.

The grid is generated rather than hand-authored so a cell's filename, its
`name` field, and its `ops_per_group` cannot drift apart -- a mismatch there
looks like a real result rather than a typo.

    python3 scenarios/gen-divergence-grid.py            # write scenarios/*.toml
    python3 scenarios/gen-divergence-grid.py --check    # verify on-disk == generated
    just gen-scenarios

Writing is idempotent: re-running over an unchanged grid rewrites identical
bytes. `--check` is the CI-friendly form -- it exits non-zero if any file is
missing or stale, without touching the working tree.
"""

import argparse
import sys
from pathlib import Path

# Ops applied by *each* side during the partition, as powers of ten. The total
# op count per trial is twice this (two singleton groups).
EXPONENTS = [2, 3, 4, 5]

# Edit-locality rules, in increasing anchor-contention order. Must match the
# `Locality` variants in crates/orchestrator/src/topology.rs (snake_case).
LOCALITIES = ["append", "random_position", "same_region"]

# One-line gloss per locality, inlined into each cell's header comment.
LOCALITY_BLURB = {
    "append": "each op inserts at the current end -- the low-contention floor",
    "random_position": "each op inserts at a uniformly-random position",
    "same_region": "every op prepends at the same anchor -- maximal contention",
}

# The document that each replica of a main-grid cell holds before the partition: the
# LaTeX paper of crdt-benchmarks B4, with its full edit history. All three localities
# start from it, so the locality axis changes only the shape of the conflict. These
# values match the B4 workload in `workloads/crdt-benchmarks.toml`.
BASELINE = """\
[partition_heal.baseline]
trace = "editing-traces/automerge-paper.json.gz"
sha256 = "42c0ff1720c0cad77077e190e36135c9cab9f7bbc266351c0a7fe4981c6a1546"
length = 104852

"""

# The control cells start from an empty document. Compare them with the main-grid
# cell of the same locality and size, to see what the starting document alone costs.
CONTROL_EXPONENTS = [3, 4]

SCENARIO_DIR = Path(__file__).resolve().parent


def cell_name(locality: str, exponent: int, empty: bool = False) -> str:
    start = "-empty" if empty else ""
    return f"divergence-n2-{locality}{start}-1e{exponent}"


def cell_toml(locality: str, exponent: int, empty: bool = False) -> str:
    """Render one grid cell. Field order matches the hand-written 1e2 cells."""
    ops = 10**exponent
    if empty:
        start = "an empty document (a control cell)"
        baseline = ""
    else:
        start = "the B4 paper, 104,852 characters"
        baseline = BASELINE
    return f"""\
# Generated by scenarios/gen-divergence-grid.py -- do not edit by hand; re-run
# the generator to refresh. One cell of the RQ-1 offline-divergence grid
# (ops-per-side x edit-locality).
#
# 2 replicas start from {start}, partition into
# singleton groups, each applies {ops:,} text-splice ops, then heal and measure
# convergence.
#
# locality = {locality}: {LOCALITY_BLURB[locality]}.
name = "{cell_name(locality, exponent, empty)}"

[partition_heal]
node_count = 2
write_pattern = "concentrated"
workload = "text_splice"
locality = "{locality}"
ops_per_group = {ops}

{baseline}[[partition_heal.groups]]
nodes = [0]

[[partition_heal.groups]]
nodes = [1]
"""


def grid() -> list[tuple[Path, str]]:
    """The main grid, then the control cells, as (path, content) pairs."""
    main = [
        (SCENARIO_DIR / f"{cell_name(loc, exp)}.toml", cell_toml(loc, exp))
        for loc in LOCALITIES
        for exp in EXPONENTS
    ]
    control = [
        (
            SCENARIO_DIR / f"{cell_name(loc, exp, empty=True)}.toml",
            cell_toml(loc, exp, empty=True),
        )
        for loc in LOCALITIES
        for exp in CONTROL_EXPONENTS
    ]
    return main + control


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument(
        "--check",
        action="store_true",
        help="verify the on-disk grid matches the generator; write nothing",
    )
    args = p.parse_args()

    stale: list[Path] = []
    for path, content in grid():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_text(content)
            print(f"{'updated' if current is not None else 'wrote'} {path.name}")

    if args.check and stale:
        print(
            "error: divergence grid is stale or incomplete; run "
            "`just gen-scenarios`. Affected:",
            file=sys.stderr,
        )
        for path in stale:
            print(f"  {path.name}", file=sys.stderr)
        return 1

    n = len(grid())
    print(f"divergence grid {'checked' if args.check else 'generated'}: {n} cells")
    return 0


if __name__ == "__main__":
    sys.exit(main())
